import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {createInterface} from 'node:readline';
import {Client} from '@modelcontextprotocol/sdk/client/index.js';
import {StdioClientTransport} from '@modelcontextprotocol/sdk/client/stdio.js';
import {waitFor,root} from './helpers.mjs';

const installedRoot=process.argv[2];
if(!installedRoot)throw new Error('Pass the installed plugin directory');
const reportPath=join(root,'../local-plugin-install/installed-settings-local8.json');
const input=createInterface({input:process.stdin});
const coordinates=input[Symbol.asyncIterator]();
const report={date:new Date().toISOString(),checks:[],passed:false};
const manifest=JSON.parse(await readFile(join(installedRoot,'plugin.json'),'utf8'));report.version=manifest.version;
const transport=new StdioClientTransport({command:join(installedRoot,'launch.sh'),args:[],cwd:installedRoot,stderr:'pipe'});
transport.stderr?.resume();
const client=new Client({name:'installed-settings-verifier',version:'1.0.0'});
const meta=r=>{assert.ok(!r.isError,r.content[0]?.text);return JSON.parse(r.content.find(c=>c.type==='text').text);};
const pass=name=>{report.checks.push(name);console.log('PASS '+name);};
try{
 await client.connect(transport);
 const tools=await client.listTools();assert.equal(tools.tools.length,15);pass('installed package starts with all 15 MCP tools');
 const call=(name,args={})=>client.callTool({name,arguments:args});
 const status=meta(await call('computer_status'));assert.equal(status.desktopConfigured,true);
 const observed=await waitFor(async()=>{const r=await call('desktop_observe',{capture:'none'}),o=meta(r);return o.accessibility.controls.some(c=>c.name==='Back'&&c.role==='button')?{r,o}:false;},10000);
 assert.equal(observed.r.content.some(c=>c.type==='image'),false);
 report.isolation=observed.o.isolation;assert.equal(report.isolation.kind,'xvfb');assert.equal(report.isolation.managed,true);
 const back=observed.o.accessibility.controls.find(c=>c.name==='Back'&&c.role==='button');
 report.back=back;assert.equal(back.states.includes('enabled'),false);assert.equal(back.sensitive,true);assert.equal(back.enabled,true);assert.equal(back.available,true);assert.ok(back.supportedActions.includes('click'));
 pass('real GTK4 Settings Back has SENSITIVE without ENABLED, normalized as available');
 const clicked=await call('desktop_controls',{actions:[{type:'click',ref:back.ref}],capture:'none'});meta(clicked);assert.equal(clicked.content.some(c=>c.type==='image'),false);
 const system=await waitFor(async()=>{const o=meta(await call('desktop_observe',{capture:'none'}));return ['Remote Desktop','Secure Shell','Users'].every(n=>o.accessibility.controls.some(c=>c.name===n))?o:false;});
 report.entries=system.accessibility.controls.filter(c=>['Remote Desktop','Secure Shell','Users'].includes(c.name));report.navigationVerified=true;
 pass('native reference click navigates to System, verified by fresh observation without screenshot or mouse');
 const remote=system.accessibility.controls.find(c=>c.name==='Remote Desktop');assert.deepEqual(remote.supportedActions,[]);
 const fallbackResult=await call('desktop_controls',{actions:[{type:'click',ref:remote.ref}],capture:'none'});
 const fallback=meta(fallbackResult);assert.equal(fallback.status,'needs_pixel_action');
 assert.equal(fallback.fallback.reason,'missing_native_click_action');assert.equal(fallback.fallback.completedActions,0);
 assert.deepEqual(fallback.fallback.pendingActions,[{type:'click',ref:remote.ref}]);
 const screenshot=fallbackResult.content.find(c=>c.type==='image');assert.equal(screenshot?.mimeType,'image/png');
 const screenshotPath=join(root,'../local-plugin-install/settings-fallback-local8.png');
 await writeFile(screenshotPath,Buffer.from(screenshot.data,'base64'));
 report.fallback=fallback.fallback;report.fallbackScreenshot=screenshotPath;
 pass('missing native click automatically returns PNG and pending action, without reporting completion');
 console.log('FALLBACK_READY '+screenshotPath+'; inspect image and supply {"x":number,"y":number}');
 const next=await coordinates.next();assert.equal(next.done,false,'Expected visually verified coordinates');
 const point=JSON.parse(next.value);assert.ok(Number.isInteger(point.x)&&Number.isInteger(point.y));
 assert.ok(point.x>=0&&point.x<fallback.width&&point.y>=0&&point.y<fallback.height);
 meta(await call('desktop_act',{actions:[{type:'click',x:point.x,y:point.y}],capture:'none'}));
 const destination=await waitFor(async()=>{const o=meta(await call('desktop_observe',{capture:'none'}));return ['Desktop Sharing','Remote Login'].every(n=>o.accessibility.controls.some(c=>c.name===n))?o:false;});
 report.pixelPoint=point;report.destination=destination.accessibility.controls.filter(c=>['Desktop Sharing','Remote Login'].includes(c.name));
 pass('screenshot-guided pixel continuation enters Remote Desktop overview, verified by fresh tree');
 const final=await call('desktop_observe',{capture:'png'});const image=final.content.find(c=>c.type==='image');assert.ok(image);
 const finalPath=join(root,'../local-plugin-install/verified-remote-desktop-local8.png');
 await writeFile(finalPath,Buffer.from(image.data,'base64'));
 report.screenshot=finalPath;report.settingsOrPasswordsChanged=false;report.passed=true;
}catch(error){report.error=error.message;throw error;}
finally{input.close();await writeFile(reportPath,JSON.stringify(report,null,2));await client.close().catch(()=>{});await transport.close().catch(()=>{});}
